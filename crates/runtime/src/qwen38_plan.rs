    #[test]
    fn mlp_carrier_inventory_accepts_only_shared_storage_topologies() {
        let target = QWEN38_MLP_FUSION_PLAN
            .iter()
            .filter(|descriptor| descriptor.role == Qwen38PlanRole::Target)
            .collect::<Vec<_>>();
        let mut pairs = std::collections::BTreeMap::new();
        for descriptor in &target {
            *pairs
                .entry((descriptor.qtypes[0], descriptor.qtypes[1]))
                .or_insert(0usize) += 1;
        }
        assert_eq!(
            pairs.into_iter().collect::<Vec<_>>(),
            vec![
                ((11, 23), 1),
                ((12, 12), 3),
                ((12, 13), 7),
                ((12, 23), 3),
                ((13, 13), 18),
                ((13, 20), 1),
                ((14, 13), 2),
                ((14, 14), 2),
                ((20, 13), 1),
                ((20, 23), 1),
                ((23, 11), 2),
                ((23, 12), 3),
                ((23, 13), 4),
                ((23, 23), 16),
            ],
        );

        let compatible = target
            .iter()
            .filter(|descriptor| descriptor.carrier_compatible())
            .count();
        let q6 = target
            .iter()
            .filter(|descriptor| descriptor.qtypes[..2].contains(&14))
            .count();
        let mixed_sidecars = target
            .iter()
            .filter(|descriptor| {
                !descriptor.qtypes[..2].contains(&14)
                    && (matches!(descriptor.qtypes[0], 13 | 21)
                        != matches!(descriptor.qtypes[1], 13 | 21))
            })
            .count();
        let different_bits = target.len() - compatible - q6 - mixed_sidecars;
        assert_eq!(
            (compatible, mixed_sidecars, different_bits, q6),
            (41, 13, 6, 4),
        );
        assert!(QWEN38_MLP_FUSION_PLAN[64].carrier_compatible());
    }

    #[test]
    fn fusion_plan_excludes_only_q6_projection_groups() {
        let excluded_mlp = QWEN38_MLP_FUSION_PLAN
            .iter()
            .filter(|descriptor| !descriptor.all_affine())
            .map(|descriptor| descriptor.layer)
            .collect::<Vec<_>>();
        assert_eq!(excluded_mlp, [56, 57, 58, 59, 60, 63]);
        assert_eq!(
            QWEN38_MLP_FUSION_PLAN
                .iter()
                .filter(|descriptor| descriptor.all_affine())
                .count(),
            59
        );

        let excluded_gdn = QWEN38_GDN_FUSION_PLAN
            .iter()
            .filter(|descriptor| !descriptor.all_affine())
            .map(|descriptor| descriptor.layer)
            .collect::<Vec<_>>();
        assert_eq!(excluded_gdn, [6, 28]);
        assert_eq!(
            QWEN38_GDN_FUSION_PLAN
                .iter()
                .filter(|descriptor| descriptor.all_affine())
                .count(),
            46
        );
    }
